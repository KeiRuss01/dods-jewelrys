-- DOD'S Jewelry Supabase schema
-- Run this migration in a new Supabase project before starting the app.

create type public.user_role as enum ('customer', 'admin');

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name varchar(100) not null,
  email varchar(255) not null unique,
  mobile_number varchar(20),
  role public.user_role not null default 'customer',
  created_at timestamptz not null default now()
);

create table public.products (
  product_id bigint generated by default as identity primary key,
  product_name varchar(100) not null,
  category varchar(50) not null,
  purity varchar(30),
  material varchar(50) not null,
  price numeric(10, 2) not null check (price >= 0),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  description text,
  product_image text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.product_images (
  image_id bigint generated by default as identity primary key,
  product_id bigint not null references public.products (product_id) on delete cascade,
  image_path text not null,
  is_primary boolean not null default false,
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default now(),
  unique (product_id, image_path)
);

create index profiles_role_idx on public.profiles (role);
create index products_active_created_idx
  on public.products (is_active, created_at desc);
create index product_images_product_order_idx
  on public.product_images (product_id, is_primary desc, sort_order);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (
    id,
    full_name,
    email,
    mobile_number,
    role
  ) values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), 'Customer'),
    lower(new.email),
    nullif(trim(new.raw_user_meta_data ->> 'mobile_number'), ''),
    'customer'
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.product_images enable row level security;

revoke all on table public.profiles from anon, authenticated;
revoke all on table public.products from anon, authenticated;
revoke all on table public.product_images from anon, authenticated;

grant select on table public.profiles to authenticated;
grant select on table public.products to anon, authenticated;
grant insert, update, delete on table public.products to authenticated;
grant select on table public.product_images to anon, authenticated;
grant insert, update, delete on table public.product_images to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create policy "Users can read their own profile"
  on public.profiles for select
  to authenticated
  using ((select auth.uid()) = id);

create policy "Admins can read profiles"
  on public.profiles for select
  to authenticated
  using ((select public.is_admin()));

create policy "Anyone can read active products"
  on public.products for select
  to anon, authenticated
  using (is_active = true);

create policy "Admins can read all products"
  on public.products for select
  to authenticated
  using ((select public.is_admin()));

create policy "Admins can create products"
  on public.products for insert
  to authenticated
  with check ((select public.is_admin()));

create policy "Admins can update products"
  on public.products for update
  to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy "Admins can delete products"
  on public.products for delete
  to authenticated
  using ((select public.is_admin()));

create policy "Anyone can read images for active products"
  on public.product_images for select
  to anon, authenticated
  using (
    exists (
      select 1
      from public.products
      where products.product_id = product_images.product_id
        and products.is_active = true
    )
  );

